"""SentinelX AI - Agent Contracts and Schemas

Typed message interfaces for specialized agents:
- Detection Agent
- Investigation and Correlation Agent
- Risk Assessment Agent
- Mitigation Planning Agent
- Reinforcement Learning Policy Component

Includes strict validation enforcing that all proposed actions belong to the action catalogue allowlist.
"""

from datetime import datetime
from typing import Any, Dict, List, Optional
from pydantic import Field, field_validator, model_validator
from .common import (
    ActionType,
    AgentName,
    AgentRunStatus,
    SentinelBaseModel,
    ensure_utc_datetime,
)
from .evidence import EvidenceReference
from .events import ID_PATTERN


class AgentTask(SentinelBaseModel):
    """Task dispatch payload from Incident Orchestrator to an Agent."""
    task_id: str = Field(..., description="Unique task identifier")
    incident_id: str = Field(..., description="Target incident identifier")
    agent_name: AgentName = Field(..., description="Target specialized agent")
    parameters: Dict[str, Any] = Field(default_factory=dict, description="Input parameters and scope")
    created_at: datetime = Field(..., description="Task dispatch timestamp in UTC")

    @field_validator("task_id", "incident_id")
    @classmethod
    def validate_ids(cls, value: str) -> str:
        if not ID_PATTERN.match(value):
            raise ValueError(f"Invalid identifier format '{value}'.")
        return value

    @field_validator("created_at")
    @classmethod
    def validate_utc(cls, value: datetime) -> datetime:
        return ensure_utc_datetime(value)


class AgentRunResult(SentinelBaseModel):
    """Standardized output produced by any SentinelX agent execution."""
    agent_run_id: str = Field(
        ...,
        description="Unique execution run identifier (e.g. run-inv-0001)"
    )
    agent_name: AgentName = Field(
        ...,
        description="Specialized agent identity"
    )
    incident_id: str = Field(
        ...,
        description="Associated incident identifier"
    )
    status: AgentRunStatus = Field(
        ...,
        description="Execution status (completed, failed, timeout)"
    )
    findings: List[EvidenceReference] = Field(
        default_factory=list,
        description="Structured evidence generated by the agent with full provenance"
    )
    # STRICT ACTION ALLOWLIST: Only ActionType enum values are allowed!
    proposed_actions: List[ActionType] = Field(
        default_factory=list,
        description="Candidate actions proposed by the agent (strictly validated against action allowlist)"
    )
    conflict_flags: List[str] = Field(
        default_factory=list,
        description="Explicit markers of conflicting, missing, or contradictory evidence"
    )
    summary: str = Field(
        ...,
        min_length=5,
        max_length=1000,
        description="Analyst-facing summary of agent findings and reasoning"
    )
    structured_output: Dict[str, Any] = Field(
        default_factory=dict,
        description="Agent-specific domain payload (e.g. timeline clusters, risk matrices, mitigation cost estimates)"
    )
    duration_ms: float = Field(
        ...,
        ge=0.0,
        description="Agent execution time in milliseconds"
    )
    created_at: datetime = Field(
        ...,
        description="Timestamp when agent run completed in UTC"
    )

    @field_validator("agent_run_id", "incident_id")
    @classmethod
    def validate_ids(cls, value: str) -> str:
        if not ID_PATTERN.match(value):
            raise ValueError(f"Invalid identifier format '{value}'.")
        return value

    @field_validator("created_at")
    @classmethod
    def validate_utc(cls, value: datetime) -> datetime:
        return ensure_utc_datetime(value)

    @model_validator(mode="after")
    def validate_agent_constraints(self) -> "AgentRunResult":
        # Detection and investigation agents cannot propose mitigation actions directly
        agent_val = str(self.agent_name.value if hasattr(self.agent_name, "value") else self.agent_name)
        if agent_val in (AgentName.DETECTION_AGENT.value, AgentName.INVESTIGATION_AGENT.value):
            if self.proposed_actions:
                raise ValueError(
                    f"Agent '{agent_val}' is analytical only and cannot propose executable actions."
                )
        return self
