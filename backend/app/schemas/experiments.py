"""SentinelX AI - Experiment Configuration and Reproducibility Schemas

Guarantees experimental provenance, recording seeds, model versions,
hyperparameters, and benchmark metrics across training and evaluation runs.
"""

from datetime import datetime
from typing import Any, Dict, List, Optional
from pydantic import Field, field_validator, model_validator
from .common import (
    ExperimentMode,
    ExperimentStatus,
    SentinelBaseModel,
    ensure_utc_datetime,
)
from .events import ID_PATTERN


class ExperimentConfig(SentinelBaseModel):
    """Specification for an offline ML or RL benchmark experiment."""
    experiment_id: str = Field(..., description="Unique experiment identifier (e.g. exp-demo-0001)")
    name: str = Field(..., min_length=3, max_length=100, description="Descriptive experiment title")
    dataset_id: str = Field(..., min_length=2, max_length=64, description="Target dataset identifier")
    model_name: str = Field(..., min_length=2, max_length=64, description="Detection model algorithm")
    policy_name: str = Field(..., min_length=2, max_length=64, description="Defensive response policy name")
    random_seed: int = Field(default=42, description="Random seed for deterministic reproducibility")
    hyperparameters: Dict[str, Any] = Field(
        default_factory=dict,
        description="Dictionary of model/RL training hyperparameters"
    )
    mode: ExperimentMode = Field(..., description="Operational mode (training or evaluation)")
    created_at: datetime = Field(..., description="Experiment configuration timestamp in UTC")

    @field_validator("experiment_id")
    @classmethod
    def validate_experiment_id(cls, value: str) -> str:
        if not ID_PATTERN.match(value):
            raise ValueError(f"Invalid experiment_id format '{value}'.")
        return value

    @field_validator("created_at")
    @classmethod
    def validate_utc(cls, value: datetime) -> datetime:
        return ensure_utc_datetime(value)


class ExperimentResult(SentinelBaseModel):
    """Results and benchmark metrics generated by an experiment run."""
    experiment_id: str = Field(..., description="Target experiment identifier")
    status: ExperimentStatus = Field(..., description="Experiment execution status")
    metrics: Dict[str, float] = Field(
        default_factory=dict,
        description="Measured metrics (e.g. precision, recall, f1, mean_cumulative_reward, containment_rate)"
    )
    confusion_matrix: Optional[List[List[int]]] = Field(
        default=None,
        description="2D confusion matrix array for classification benchmarks"
    )
    artifact_path: Optional[str] = Field(
        default=None,
        max_length=256,
        description="Local path to serialized model or policy artifact"
    )
    error_message: Optional[str] = Field(
        default=None,
        max_length=1000,
        description="Failure reason if experiment failed"
    )
    started_at: datetime = Field(..., description="Run start timestamp in UTC")
    completed_at: Optional[datetime] = Field(default=None, description="Run completion timestamp in UTC")

    @field_validator("experiment_id")
    @classmethod
    def validate_experiment_id(cls, value: str) -> str:
        if not ID_PATTERN.match(value):
            raise ValueError(f"Invalid experiment_id format '{value}'.")
        return value

    @field_validator("started_at", "completed_at")
    @classmethod
    def validate_utc(cls, value: Optional[datetime]) -> Optional[datetime]:
        if value is not None:
            return ensure_utc_datetime(value)
        return None

    @model_validator(mode="after")
    def validate_run_lifecycle(self) -> "ExperimentResult":
        if self.status == ExperimentStatus.COMPLETED and self.completed_at is None:
            raise ValueError("Completed experiment must provide completed_at timestamp.")
        if self.completed_at is not None and self.completed_at < self.started_at:
            raise ValueError("completed_at cannot be earlier than started_at.")
        if self.status == ExperimentStatus.FAILED and not self.error_message:
            raise ValueError("Failed experiment must include an error_message.")
        return self
